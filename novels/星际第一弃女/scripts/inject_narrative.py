def inject(fname, text):
    key = os.path.basename(fname).split('_')[1]  # 第001章
    injs = INJECTIONS.get(key, [])
    if not injs:
        return text, 0
    added = 0
    for anchor, new_para in injs:
        if anchor in text and new_para.split('\n')[0] not in text:
            # 在锚点段落之后插入新叙事段
            idx = text.find(anchor)
            # 找到该段落的结尾（下一个\n\n）
            end = text.find('\n\n', idx)
            if end == -1: end = len(text)
            text = text[:end] + '\n\n' + new_para + text[end:]
            added += 1
    return text, added

if __name__ == '__main__':
    total = 0
    for f in sorted(glob.glob('chapters/*.md')):
        text = open(f, encoding='utf-8').read()
        new_text, n = inject(f, text)
        if n:
            open(f, 'w', encoding='utf-8').write(new_text)
            print(f'{os.path.basename(f)}: 注入 {n} 段叙事')
            total += n
        else:
            print(f'{os.path.basename(f)}: 无注入')
    print(f'总计注入 {total} 段')
